/**
 * School branding for reports (print / PDF / Excel / CSV).
 * Expected shape: { name, logo, address, phone, email }
 */

export function normalizeSchoolBranding(raw = {}) {
  const src = raw?.school || raw || {};
  return {
    name: String(src.name || src.school_name || "").trim(),
    logo: String(src.logo || src.school_logo || "").trim(),
    address: String(src.address || "").trim(),
    phone: String(src.phone || src.contact_phone || "").trim(),
    email: String(src.email || src.contact_email || "").trim(),
  };
}

export function brandingContactLine(branding) {
  const b = normalizeSchoolBranding(branding);
  return [b.phone, b.email].filter(Boolean).join(" · ");
}

export function brandingFooterLines(branding) {
  const b = normalizeSchoolBranding(branding);
  const lines = [];
  if (b.address) lines.push(b.address);
  const contact = brandingContactLine(b);
  if (contact) lines.push(contact);
  return lines;
}

function escapeHtml(value) {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

/** HTML header block for print/PDF */
export function buildReportHeaderHtml(branding, { title = "", subtitle = "" } = {}) {
  const b = normalizeSchoolBranding(branding);
  const logo = b.logo
    ? `<img class="brand-logo" src="${escapeHtml(b.logo)}" alt="" />`
    : `<div class="brand-logo-fallback">${escapeHtml(
        (b.name || "S").slice(0, 1).toUpperCase(),
      )}</div>`;

  return `
  <header class="report-header">
    <div class="brand-row">
      ${logo}
      <div class="brand-text">
        <div class="brand-name">${escapeHtml(b.name || "School")}</div>
        ${
          b.address
            ? `<div class="brand-sub">${escapeHtml(b.address)}</div>`
            : ""
        }
      </div>
    </div>
    ${title ? `<h1 class="report-title">${escapeHtml(title)}</h1>` : ""}
    ${
      subtitle
        ? `<p class="report-subtitle">${escapeHtml(subtitle)}</p>`
        : ""
    }
  </header>`;
}

/** HTML footer block for print/PDF */
export function buildReportFooterHtml(branding) {
  const lines = brandingFooterLines(branding);
  if (!lines.length) {
    return `<footer class="report-footer"><span>Generated by EduAitor</span></footer>`;
  }
  return `
  <footer class="report-footer">
    ${lines.map((l) => `<div>${escapeHtml(l)}</div>`).join("")}
  </footer>`;
}

/**
 * Prepend school branding + title rows and append footer for Excel (aoa).
 * @returns {any[][]}
 */
export function wrapExcelWithBranding(
  dataRows = [],
  branding,
  { title = "Report", subtitle = "" } = {},
) {
  const b = normalizeSchoolBranding(branding);
  const header = [
    [b.name || "School"],
    ...(b.address ? [[b.address]] : []),
    ...(brandingContactLine(b) ? [[brandingContactLine(b)]] : []),
    [""],
    [title],
    ...(subtitle ? [[subtitle]] : []),
    [""],
  ];
  const footer = [
    [""],
    ...brandingFooterLines(b).map((line) => [line]),
  ];
  return [...header, ...dataRows, ...footer];
}

/** Prepend branding lines for CSV row arrays */
export function wrapCsvWithBranding(
  dataRows = [],
  branding,
  { title = "Report", subtitle = "" } = {},
) {
  return wrapExcelWithBranding(dataRows, branding, { title, subtitle });
}

