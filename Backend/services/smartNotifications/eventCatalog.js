function evt(def) {
  return {
    defaultRecipients: ["parent"],
    defaultChannels: ["in_app", "push"],
    urgent: false,
    respectQuietHours: true,
    defaultEnabled: true,
    timing: { mode: "immediate", offsetMinutes: 0 },
    ...def,
  };
}

