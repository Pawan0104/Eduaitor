export const EVENT_TYPES = Object.keys(EVENT_CATALOG);

export function getEventDefinition(eventType) {
  return EVENT_CATALOG[eventType] || null;
}

export function listEventsByCategory() {
  return CATEGORIES.map((cat) => ({
    ...cat,
    events: EVENT_TYPES.filter((id) => EVENT_CATALOG[id].category === cat.id).map(
      (id) => EVENT_CATALOG[id],
    ),
  }));
}
