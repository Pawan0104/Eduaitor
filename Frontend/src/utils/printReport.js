/**
 * Reliable print / "Save as PDF" for report pages.
 * Uses a hidden iframe (no pop-up). Do not use window.open(..., "noopener") —
 * modern browsers return null and print never runs.
 */

import {
  REPORT_BRAND_STYLES,
  buildReportFooterHtml,
  buildReportHeaderHtml,
  normalizeSchoolBranding,
} from "./reportBranding";

const DEFAULT_STYLES = `
  body {
    font-family: Arial, Helvetica, sans-serif;
    color: #111;
    padding: 24px;
    margin: 0;
    background: #fff;
  }
  h1, h2, h3 { margin: 0 0 8px; color: #111; }
  h1 { font-size: 20px; }
  h2 { font-size: 16px; }
  p { margin: 4px 0; color: #444; font-size: 12px; }
  table { width: 100%; border-collapse: collapse; margin-top: 12px; font-size: 12px; }
  th, td { border: 1px solid #ddd; padding: 8px; text-align: left; vertical-align: top; }
  th { background: #f5f5f5; font-weight: 700; }
  .print-muted { color: #666; font-size: 11px; }
  .print-card {
    border: 1px solid #e5e7eb;
    border-radius: 8px;
    padding: 12px;
    margin-bottom: 12px;
  }
  .print-grid {
    display: grid;
    grid-template-columns: repeat(2, minmax(0, 1fr));
    gap: 8px;
    margin-bottom: 12px;
  }
  @media print {
    body { padding: 12px; }
    a { color: inherit; text-decoration: none; }
  }
  ${REPORT_BRAND_STYLES}
`;

function escapeHtml(value) {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

/**
 * @param {object} opts
 * @param {string} opts.title
 * @param {string} opts.bodyHtml
 * @param {string} [opts.subtitle]
 * @param {object} [opts.branding] school { name, logo, address, phone, email }
 * @param {boolean} [opts.asPdf]
 */
export function printReportHtml({
  title = "Report",
  subtitle = "",
  bodyHtml = "",
  branding = null,
  asPdf = false,
  onInfo,
  onError,
} = {}) {
  try {
    const frame = document.createElement("iframe");
    frame.setAttribute("aria-hidden", "true");
    frame.style.position = "fixed";
    frame.style.right = "0";
    frame.style.bottom = "0";
    frame.style.width = "0";
    frame.style.height = "0";
    frame.style.border = "0";
    frame.style.opacity = "0";
    frame.style.pointerEvents = "none";
    document.body.appendChild(frame);

    const win = frame.contentWindow;
    const doc = win?.document;
    if (!win || !doc) {
      frame.remove();
      onError?.("Could not prepare print view.");
      return false;
    }

    const brand = normalizeSchoolBranding(branding);
    const hasBrand = Boolean(brand.name || brand.logo);
    const headerHtml = hasBrand
      ? buildReportHeaderHtml(brand, { title, subtitle })
      : `<h1>${escapeHtml(title)}</h1>${
          subtitle
            ? `<p class="print-muted">${escapeHtml(subtitle)}</p>`
            : ""
        }`;
    const footerHtml = hasBrand
      ? buildReportFooterHtml(brand)
      : `<footer class="report-footer"><span>Generated by EduAitor</span></footer>`;

    const docTitle = escapeHtml(
      brand.name ? `${brand.name} — ${title}` : title,
    );

    doc.open();
    doc.write(`<!doctype html>
<html>
<head>
  <meta charset="utf-8" />
  <title>${docTitle}</title>
  <style>${DEFAULT_STYLES}</style>
</head>
<body>
  ${headerHtml}
  <main class="report-body">${bodyHtml}</main>
  ${footerHtml}
</body>
</html>`);
    doc.close();

    let cleaned = false;
    const cleanup = () => {
      if (cleaned) return;
      cleaned = true;
      try {
        frame.remove();
      } catch {
        /* ignore */
      }
    };

    const doPrint = () => {
      try {
        win.focus();
        win.print();
      } catch (err) {
        onError?.(err?.message || "Print failed");
        cleanup();
        return;
      }
      if (asPdf) {
        onInfo?.(
          "In the print dialog, choose Save as PDF / Microsoft Print to PDF.",
        );
      }
    };

    // Wait for logo image if present
    const imgs = [...(doc.images || [])];
    const pending = imgs.filter((img) => !img.complete);
    if (pending.length) {
      let left = pending.length;
      const done = () => {
        left -= 1;
        if (left <= 0) setTimeout(doPrint, 50);
      };
      pending.forEach((img) => {
        img.addEventListener("load", done);
        img.addEventListener("error", done);
      });
      setTimeout(doPrint, 1500);
    } else {
      setTimeout(doPrint, 250);
    }

    win.addEventListener("afterprint", cleanup);
    setTimeout(cleanup, 120000);
    return true;
  } catch (err) {
    onError?.(err?.message || "Print failed");
    return false;
  }
}

/**
 * Print a DOM node's content (clone innerHTML) with school branding.
 */
export function printReportElement(
  target,
  { title, subtitle, branding, asPdf, onInfo, onError } = {},
) {
  const el =
    typeof target === "string" ? document.getElementById(target) : target;
  if (!el) {
    onError?.("Nothing to print — load a report first.");
    return false;
  }

  const clone = el.cloneNode(true);
  clone
    .querySelectorAll("button, input, select, textarea, .print\\:hidden")
    .forEach((node) => node.remove());

  return printReportHtml({
    title: title || document.title || "Report",
    subtitle,
    bodyHtml: clone.innerHTML,
    branding,
    asPdf,
    onInfo,
    onError,
  });
}
